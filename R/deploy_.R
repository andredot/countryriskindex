# Deploying the live scoring app without installing the package.
#
# A deployment server (shinyapps.io, Posit Connect) installs every package the
# app uses from a repository. countryriskindex is not on CRAN, so the app is
# deployed as a self-contained folder instead: app.R sources the few R files
# the app needs, and the static inputs travel with it.

#' R files needed by the live scoring app
#'
#' The files defining [run_scoring_app()] and everything it calls. Files used
#' only by the pipeline or the report (maps, PCA, sensitivity analysis) are
#' left out, so that deployment does not install their packages.
#'
#' @return A character vector of file names within `R/`.
#' @export
scoring_app_files <- function() {
  c("add_.R", "calculator_.R", "compare_.R", "explain_.R", "functions.R",
    "import_.R", "preprocess_.R", "scoring_app_.R", "severity_.R",
    "small_utils.R", "utils.R", "weights_.R")
}

#' Build a deployable folder for the live scoring app
#'
#' Writes a folder that runs [run_scoring_app()] on its own, without the
#' countryriskindex package being installed:
#' \itemize{
#'   \item `app.R`, which sources the files in `R/` and starts the app;
#'   \item `R/`, the files listed by [scoring_app_files()];
#'   \item `inst/extdata/`, the crisis modifier matrix and the reference
#'     quantiles;
#'   \item `data/`, the static inputs (location keys, HAQI) and the local
#'     copies of the WHO indicators, used when the download fails;
#'   \item `data/baseline.rds`, the headline scores to compare against, when
#'     `baseline` is given.
#' }
#' Deploy it with `rsconnect::deployApp(appDir = <the folder>)`; see
#' `dev/06-deploy_scoring_app.R`. Users of the deployed app upload only the GBD
#' and INFORM files.
#'
#' @param dir Folder to write. Its previous content is replaced.
#' @param defaults Named vector of local paths of the inputs, see
#'   [default_risk_input_paths()].
#' @param baseline Optional scored data frame to compare against, e.g.
#'   `targets::tar_read(risk_score)`. Only the headline columns are kept.
#' @param project Project root holding `R/` and `inst/extdata/`.
#'
#' @return The path of `dir`, invisibly.
#' @export
build_scoring_bundle <- function(dir = "deploy/scoring_app",
                                 defaults = default_risk_input_paths(),
                                 baseline = NULL,
                                 project = ".") {
  files <- risk_input_files()
  defaults <- complete_defaults(defaults, files)

  if (dir.exists(dir)) unlink(dir, recursive = TRUE)
  for (sub in c("R", "data", file.path("inst", "extdata"))) {
    dir.create(file.path(dir, sub), recursive = TRUE, showWarnings = FALSE)
  }

  r_files <- file.path(project, "R", scoring_app_files())
  stopifnot(all(file.exists(r_files)))
  file.copy(r_files, file.path(dir, "R"))

  extdata <- list.files(file.path(project, "inst", "extdata"),
                        full.names = TRUE)
  file.copy(extdata, file.path(dir, "inst", "extdata"))

  # Inputs that are not uploaded: static tables, and WHO copies as fallback.
  bundled <- stats::setNames(rep(NA_character_, nrow(files)), files$id)
  for (i in which(files$update != "upload")) {
    id <- files$id[i]
    if (files$location[i] == "package") {
      bundled[[id]] <- file.path("inst", "extdata", basename(files$file[i]))
    } else if (!is.na(defaults[[id]]) && file.exists(defaults[[id]])) {
      target <- file.path("data", basename(defaults[[id]]))
      file.copy(defaults[[id]], file.path(dir, target), overwrite = TRUE)
      bundled[[id]] <- target
    }
  }
  missing <- files$label[files$update == "static" & is.na(bundled)]
  if (length(missing) > 0) {
    warning("Not bundled (users will be asked to upload them): ",
            paste(missing, collapse = "; "), call. = FALSE)
  }
  saveRDS(bundled, file.path(dir, "data", "defaults.rds"))

  if (!is.null(baseline)) {
    keep <- intersect(snapshot_columns(), names(baseline))
    saveRDS(as.data.frame(baseline)[, keep, drop = FALSE],
            file.path(dir, "data", "baseline.rds"))
  }

  writeLines(scoring_app_script(), file.path(dir, "app.R"))
  message("Scoring app bundle written to ", normalizePath(dir), " (",
          length(list.files(dir, recursive = TRUE)), " files).")
  invisible(dir)
}

#' Contents of the bundle's app.R
#' @noRd
scoring_app_script <- function() {
  c(
    "# Live scoring app: deployable bundle.",
    "# Generated by build_scoring_bundle() (R/deploy_.R): rebuild the bundle",
    "# rather than editing this file.",
    "",
    "for (f in list.files(\"R\", pattern = \"[.]R$\", full.names = TRUE)) {",
    "  source(f)",
    "}",
    "",
    "defaults <- readRDS(\"data/defaults.rds\")",
    "baseline <- if (file.exists(\"data/baseline.rds\")) {",
    "  readRDS(\"data/baseline.rds\")",
    "}",
    "",
    "# Used through requireNamespace(); listed so that deployment installs it.",
    "if (FALSE) library(writexl)",
    "",
    "run_scoring_app(baseline = baseline, defaults = defaults,",
    "                output_dir = NULL)"
  )
}
